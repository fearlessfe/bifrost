// The methods below are unsupported by the DashScope provider. DashScope's
// remaining native surfaces either need public file URLs (Paraformer file
// transcription), WebSocket transport (realtime ASR, CosyVoice TTS on the
// workspace domain), or have no REST API at all (containers). DashScope does
// expose an OpenAI-compatible Batch/Files surface under /compatible-mode/v1
// (limited to chat-completion and embedding jobs), but this provider
// deliberately does not wire it up yet.

// ListModels is not supported: DashScope has no stable public model-list
// endpoint.
func (provider *DashScopeProvider) ListModels(ctx *schemas.BifrostContext, keys []schemas.Key, request *schemas.BifrostListModelsRequest) (*schemas.BifrostListModelsResponse, *schemas.BifrostError) {
	return nil, providerUtils.NewUnsupportedOperationError(schemas.ListModelsRequest, provider.GetProviderKey())
}

